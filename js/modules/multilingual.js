function mlGenerateFiles() {
  if (_mlResults.length === 0) { toast('Generate translations first', 'warn'); return; }

  var count = 0;
  _mlResults.forEach(function(r) {
    var fn = 'payload_' + r.lang.replace(/\+/g, '_') + '_' + (r.type === 'mixed' ? 'mixed' : 'single');
    // Using gF from generate.js: gF(format, name, header, template, context, payload)
    if(typeof gF === 'function') {
      gF('txt', fn + '.txt', '', '', '', r.text);
      count++;
    }
  });

  if(count > 0) {
    gC += count;
    var cGEl = document.getElementById('cG');
    if (cGEl) cGEl.textContent = gC;
    toast('Generated ' + count + ' files', 'ok');
  } else {
    toast('Error: Generator engine not found', 'err');
  }
}

