/* ── Online translation via MyMemory API (free, no key) ── */
function _mlTranslateOnline(text, langCode) {
  var apiLang = ML_API_CODES[langCode] || langCode;
  var url = 'https://api.mymemory.translated.net/get?q=' +
    encodeURIComponent(text.substring(0, 500)) + '&langpair=en|' + apiLang;

  if (typeof fetch === 'undefined') {
    return Promise.reject(new Error('fetch not available'));
  }

  return fetch(url, { mode: 'cors' })
    .then(function(res) {
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res.json();
    })
    .then(function(data) {
      if (data.responseStatus === 200 && data.responseData && data.responseData.translatedText) {
        var translated = data.responseData.translatedText;
        if (translated === text.toUpperCase() || translated.indexOf('MYMEMORY WARNING') >= 0) {
          throw new Error('API quota or bad response');
        }
        return translated;
      }
      throw new Error('Unexpected API response');
    });
}

/* ── Local dictionary-based translation (offline fallback) ── */
function _mlTranslateLocal(text, langCode) {
  if (!ML_TRANSLATIONS[langCode] || langCode === 'en') return text;

  var result = text;

  // 1. Phrase-level replacements (longest-first for greedy matching)
  var phrases = ML_PHRASES[langCode] || {};
  var phraseKeys = Object.keys(phrases).sort(function(a, b) { return b.length - a.length; });
  for (var i = 0; i < phraseKeys.length; i++) {
    var eng = phraseKeys[i];
    var regex = new RegExp(eng.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
    result = result.replace(regex, phrases[eng]);
  }

  // 2. Word-level translation for remaining English words
  var vocab = ML_VOCAB[langCode];
  if (vocab) {
    var tokens = result.split(/(\s+|[.,!?;:"\[\](){}]|\n)/);
    result = tokens.map(function(token) {
      var clean = token.toLowerCase().trim();
      if (!clean) return token;
      var trans = vocab[clean];
      if (trans !== undefined) {
        if (trans === '') return '';
        if (token[0] === token[0].toUpperCase() && token[0] !== token[0].toLowerCase()) {
          return trans.charAt(0).toUpperCase() + trans.slice(1);
        }
        return trans;
      }
      return token;
    }).join('');
    result = result.replace(/  +/g, ' ').trim();
  }

  return result;
}

/* ── Translate: online with local fallback ── */
function _mlTranslatePayload(text, langCode, useOnline) {
  if (!ML_TRANSLATIONS[langCode] || langCode === 'en') {
    return Promise.resolve(text);
  }
  if (!useOnline) {
    return Promise.resolve(_mlTranslateLocal(text, langCode));
  }
  try {
    return _mlTranslateOnline(text, langCode)
      .then(function(result) { return result; })
      .catch(function(err) {
        console.warn('Online translation failed for ' + langCode + ':', err.message, '- using local fallback');
        return _mlTranslateLocal(text, langCode);
      });
  } catch (e) {
    console.warn('Online translation threw for ' + langCode + ':', e.message, '- using local fallback');
    return Promise.resolve(_mlTranslateLocal(text, langCode));
  }
}

