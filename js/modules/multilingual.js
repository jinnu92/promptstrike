function mlGenerateTranslations() {
  var base = document.getElementById('mlBasePayload').value.trim();
  if (!base) { ss('mlSt', 'err', 'Enter a base payload first.'); return; }

  var langs = _mlGetSelectedLangs();
  if (langs.length === 0) { ss('mlSt', 'err', 'Select at least one language.'); return; }

  var onlineCB = document.getElementById('mlOnlineMode');
  var useOnline = onlineCB ? onlineCB.checked : false;

  // Check if running from file:// - online won't work
  if (useOnline && window.location.protocol === 'file:') {
    useOnline = false;
    ss('mlSt', 'info', 'file:// detected - using local dictionary. Run via HTTP server for online translation.');
  }

  _mlResults = [];
  var completed = 0;
  var total = langs.length;

  ss('mlSt', 'info', 'Translating... 0/' + total + (useOnline ? ' (online)' : ' (local)'));

  // Translate sequentially to respect API rate limits
  var chain = Promise.resolve();
  langs.forEach(function(lc) {
    chain = chain.then(function() {
      return _mlTranslatePayload(base, lc, useOnline).then(function(trans) {
        var lang = ML_TRANSLATIONS[lc];
        _mlResults.push({ lang:lc, name:lang.name, flag:lang.flag, text:trans, type:'single' });
        completed++;
        ss('mlSt', 'info', 'Translating... ' + completed + '/' + total);
        _mlRenderResults();
      });
    });
  });

  chain.then(function() {
    ss('mlSt', 'ok', 'Generated ' + _mlResults.length + ' translations' + (useOnline ? ' (online).' : ' (local).'));
  }).catch(function(err) {
    ss('mlSt', 'err', 'Translation error: ' + err.message);
  });
}

